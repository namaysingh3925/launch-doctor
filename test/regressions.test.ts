test('Firebase rules that let anyone create, update or delete are caught', async () => {
  for (const rule of ['allow read, create: if true;', 'allow update: if true;', 'allow read, write;']) {
    const report = await runDoctor(
      makeProject({
        'package.json': JSON.stringify({ dependencies: { firebase: '11' } }),
        'firestore.rules': `service cloud.firestore { match /databases/{d}/documents { match /posts/{p} { ${rule} } } }`,
      }),
      opts,
    );
    assert.ok(ids(report).includes('firebase-open-rules'), `missed: ${rule}`);
  }
  const safe = await runDoctor(
    makeProject({
      'package.json': JSON.stringify({ dependencies: { firebase: '11' } }),
      'firestore.rules':
        'service cloud.firestore { match /databases/{d}/documents { match /posts/{p} { allow read: if true; allow write: if request.auth != null; } } }',
    }),
    opts,
  );
  assert.ok(!ids(safe).includes('firebase-open-rules'), 'public read + signed-in write is fine');
});

