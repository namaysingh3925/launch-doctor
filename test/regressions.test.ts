import assert from 'node:assert/strict';
import { test } from 'node:test';
import { runDoctor } from '../src/index.js';
import { matchesGitignore, packageNameOf } from '../src/project.js';
import { category, fakeKey, ids, makeProject } from './helpers.js';

const opts = { offline: true, useGit: false };

test('package.json saved with a byte-order mark is still read', async () => {
  const report = await runDoctor(
    makeProject({
      'package.json': '﻿' + JSON.stringify({ name: 'bom-app', dependencies: { vite: '7', react: '19', stripe: '18' } }),
      'src/App.tsx': 'export default () => null;\n',
    }),
    opts,
  );
  assert.equal(report.projectName, 'bom-app');
  assert.ok(report.stack.includes('Stripe'));
});

test('Deno imports with a query string are recognised', async () => {
  assert.equal(packageNameOf('https://esm.sh/stripe?target=deno'), 'stripe');
  assert.equal(packageNameOf('https://esm.sh/stripe@14.0.0?target=deno&no-check'), 'stripe');
  const report = await runDoctor(
    makeProject({
      'supabase/functions/pay/index.ts':
        "import Stripe from 'https://esm.sh/stripe?target=deno';\nDeno.serve(async (req) => {\n  const e = await req.json();\n  if (e.type === 'checkout.session.completed') {}\n  return new Response('');\n});\n",
    }),
    opts,
  );
  assert.ok(ids(report).includes('stripe-webhook-unverified'));
});

test('URL slugs starting with "sk-" are not mistaken for OpenAI keys', async () => {
  const report = await runDoctor(
    makeProject({
      'package.json': '{}',
      'src/links.ts': "export const u = 'https://blog.example.com/sk-learn-machine-learning-tutorial-for-beginners';\n",
    }),
    opts,
  );
  assert.deepEqual(category(report, 'secrets').findings, []);
});

test('newer key formats are detected and labelled correctly', async () => {
  const report = await runDoctor(
    makeProject({
      'package.json': '{}',
      'server/a.ts': `const a = "${fakeKey('sb_' + 'secret_', 32, 5)}";\n`,
      'server/b.ts': `const b = "${fakeKey('wh' + 'sec_', 32, 6)}";\n`,
      'server/c.ts': `const c = "${fakeKey('sk-' + 'or-v1-', 64, 8)}";\n`,
      'server/d.ts': `const d = "${fakeKey('gs' + 'k_', 52, 9)}";\n`,
    }),
    opts,
  );
  const found = category(report, 'secrets').findings.map((f) => `${f.id}@${f.location?.file}`);
  assert.ok(found.includes('supabase-secret-key@server/a.ts'), found.join(', '));
  assert.ok(found.includes('stripe-webhook-secret@server/b.ts'), found.join(', '));
  assert.ok(found.includes('openrouter-key@server/c.ts'), found.join(', '));
  assert.ok(found.includes('groq-key@server/d.ts'), found.join(', '));
  assert.ok(!found.some((f) => f.startsWith('openai-key')), 'OpenRouter key must not be labelled as OpenAI');
});

test('a server file inside a Vite src/ folder is not treated as browser code', async () => {
  const report = await runDoctor(
    makeProject({
      'package.json': JSON.stringify({ dependencies: { vite: '7', react: '19', express: '5', openai: '5' } }),
      'src/server.ts': "import express from 'express';\nimport OpenAI from 'openai';\nconst app = express();\napp.listen(3000);\n",
      'src/backend/routes.ts': "import express from 'express';\nimport OpenAI from 'openai';\nexport const r = express.Router();\n",
    }),
    opts,
  );
  assert.ok(!ids(report).includes('ai-in-browser'), ids(report).join(', '));
});

test('Firebase rules that let anyone create, update or delete are caught', async () => {
  for (const rule of ['allow read, create: if true;', 'allow update: if true;', 'allow read, write;']) {
    const report = await runDoctor(
      makeProject({
        'package.json': JSON.stringify({ dependencies: { firebase: '11' } }),
        'firestore.rules': `service cloud.firestore { match /databases/{d}/documents { match /posts/{p} { ${rule} } } }`,
      }),
      opts,
    );
    assert.ok(ids(report).includes('firebase-open-rules'), `missed: ${rule}`);
  }
  const safe = await runDoctor(
    makeProject({
      'package.json': JSON.stringify({ dependencies: { firebase: '11' } }),
      'firestore.rules':
        'service cloud.firestore { match /databases/{d}/documents { match /posts/{p} { allow read: if true; allow write: if request.auth != null; } } }',
    }),
    opts,
  );
  assert.ok(!ids(safe).includes('firebase-open-rules'), 'public read + signed-in write is fine');
});

test('the Next.js default description is reported as a description, not a title', async () => {
  const report = await runDoctor(
    makeProject({
      'package.json': JSON.stringify({ dependencies: { next: '16', react: '19' } }),
      'app/layout.tsx': "export const metadata = { title: 'My App', description: 'Generated by create next app' };\n",
      'app/page.tsx': 'export default () => null;\n',
    }),
    opts,
  );
  const f = category(report, 'first-impressions').findings.find((x) => x.id === 'default-title');
  assert.match(f!.title, /description/);
});

