test('newer key formats are detected and labelled correctly', async () => {
  const report = await runDoctor(
    makeProject({
      'package.json': '{}',
      'server/a.ts': `const a = "${fakeKey('sb_' + 'secret_', 32, 5)}";\n`,
      'server/b.ts': `const b = "${fakeKey('wh' + 'sec_', 32, 6)}";\n`,
      'server/c.ts': `const c = "${fakeKey('sk-' + 'or-v1-', 64, 8)}";\n`,
      'server/d.ts': `const d = "${fakeKey('gs' + 'k_', 52, 9)}";\n`,
    }),
    opts,
  );
  const found = category(report, 'secrets').findings.map((f) => `${f.id}@${f.location?.file}`);
  assert.ok(found.includes('supabase-secret-key@server/a.ts'), found.join(', '));
  assert.ok(found.includes('stripe-webhook-secret@server/b.ts'), found.join(', '));
  assert.ok(found.includes('openrouter-key@server/c.ts'), found.join(', '));
  assert.ok(found.includes('groq-key@server/d.ts'), found.join(', '));
  assert.ok(!found.some((f) => f.startsWith('openai-key')), 'OpenRouter key must not be labelled as OpenAI');
});

