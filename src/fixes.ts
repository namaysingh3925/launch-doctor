import { shortWhere } from './checks/common.js';
import type { Finding, Report } from './types.js';
import { plural } from './util.js';

function fence(text: string): string {
  // Use a fence longer than any backtick run inside the prompt.
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((m) => m.length));
  const ticks = '`'.repeat(longest + 1);
  return `${ticks}text\n${text}\n${ticks}`;
}

function section(f: Finding, n: number): string {
  const parts = [`### ${n}. ${f.title}`, ''];
  if (f.location) parts.push(`**Where:** \`${shortWhere(f.location)}\``, '');
  if (f.baseline) parts.push('_Existing issue, recorded in .launchdoctor-baseline.json._', '');
  parts.push(`**Why it matters:** ${f.why}`, '', '**Prompt to paste:**', '', fence(f.fixPrompt), '');
  parts.push(`<sub>Not relevant to your app? Add \`${f.id}\` to a \`.launchdoctorignore\` file.</sub>`, '');
  return parts.join('\n');
}

/** A markdown file of copy-paste prompts, ordered by importance. */
export function renderFixes(report: Report): string {
  const all = report.categories.flatMap((c) => c.findings);
  const critical = all.filter((f) => f.severity === 'critical');
  const warnings = all.filter((f) => f.severity === 'warning');
  const ordered = [...critical, ...warnings];
  const manual = report.categories.flatMap((c) => c.manual);
  const date = report.generatedAt.slice(0, 10);

  const out: string[] = [
    `# Launch Doctor fixes for ${report.projectName}`,
    '',
    `**Grade: ${report.grade}** · ${report.verdict} · ${plural(critical.length, 'critical issue')} · ${plural(warnings.length, 'warning')} · checked ${date}`,
    '',
    '## How to use this file',
    '',
    '1. Paste **one prompt at a time** into your AI coding tool (Claude Code, Cursor, Lovable, Bolt, Windsurf…).',
    '2. Read what it changed and test the app.',
    '3. Run `npx launch-doctor` again to see your new grade.',
    '',
  ];

  if (ordered.length) {
    out.push(
      '### Or fix everything in one go',
      '',
      fence(
        'I ran Launch Doctor on my app and it found the problems below. Fix them one at a time, in this order. ' +
          "For each one: explain the change in plain English, make it, and tell me how to test it. Don't change anything unrelated, and ask me before deleting data.\n\n" +
          ordered.map((f, i) => `${i + 1}. ${f.title}${f.location ? ` — ${shortWhere(f.location)}` : ''}`).join('\n'),
      ),
      '',
    );
  }

  if (!ordered.length) {
    out.push('## All clear - nothing to fix', '', 'Launch Doctor found no problems in your code this time.', '');
  }

  let n = 1;
  if (critical.length) {
    out.push('## Must fix before launch', '');
    for (const f of critical) out.push(section(f, n++));
  }
  if (warnings.length) {
    out.push('## Should fix', '');
    for (const f of warnings) out.push(section(f, n++));
  }
  if (manual.length) {
    out.push('## Check yourself', '');
    out.push("Things Launch Doctor can't see from your code:", '');
    for (const m of manual) out.push(`- [ ] **${m.title}** - ${m.how}`);
    out.push('');
  }

  out.push(
    '---',
    '',
    `_Generated by [Launch Doctor](https://www.npmjs.com/package/launch-doctor) v${report.version}. Safe to delete or add to .gitignore._`,
    '',
  );
  return out.join('\n');
}
