import type { SourceFile } from '../project.js';
import type { Check } from '../types.js';
import { lineTextAt } from '../util.js';
import { appCode, at, emptyOutput, notApplicable, where } from './common.js';

const DEFAULT_TITLE =
  /<title>\s*(?:Vite \+ (?:React|Vue|Svelte|Preact|Lit|Solid|TS)(?: \+ TS)?|Vite App|React App|Create Next App|Lovable App|Nuxt App|SvelteKit App)\s*<\/title>|title\s*:\s*["'`]Create Next App["'`]|Generated by create next app/i;

const LOVABLE_DEFAULTS = /Lovable Generated Project|lovable\.dev\/opengraph-image|@lovable_dev|gpt-engineer/i;

const CONFIG_OR_SCRIPT =
  /(^|\/)(vite|next|nuxt|svelte|astro|playwright|vitest|jest|webpack|tailwind|postcss|eslint|tsup|rollup)\.config\.|(^|\/)(scripts|tools|seed|e2e)\/|(^|\/)seed\.|\.md$/i;

const htmlOrLayout = (f: SourceFile) =>
  appCode(f) && (/\.html?$/i.test(f.path) || /(^|\/)(app\/layout|_document|_app|app\.html|\+layout|nuxt\.config|layouts?\/)/i.test(f.path) || /index\.html$/.test(f.path));

export const firstImpressionsCheck: Check = {
  id: 'first-impressions',
  name: 'First impressions',
  icon: '✨',
  weight: 1,
  run(ctx) {
    const frontend =
      ctx.files.some((f) => /\.html?$/i.test(f.path)) ||
      ctx.usesAny(['react', 'vue', 'svelte', 'next', 'nuxt', 'astro', '@sveltejs/kit', 'solid-js', 'preact', '@angular/core']);
    if (!frontend) return notApplicable('No website frontend found');
    const out = emptyOutput();

    // Default template titles
    const defaultTitle = ctx.find(DEFAULT_TITLE, appCode, 1)[0];
    if (defaultTitle) {
      out.findings.push({
        id: 'default-title',
        severity: 'warning',
        title: `Your browser tab still says "${defaultTitle.match[0].replace(/<\/?title>|title\s*:\s*|["'`]/gi, '').trim()}"`,
        why: "That's the starter template's title. It shows in browser tabs, Google results and shared links, and makes the app look unfinished.",
        location: at(defaultTitle),
        fixPrompt: `My app still uses the template's default page title and description (${where(at(defaultTitle))}). Replace them with my app's real name and a one-sentence description of what it does, and set a title template so each page gets its own title.`,
      });
    }

    const lovable = ctx.find(LOVABLE_DEFAULTS, appCode, 1)[0];
    if (lovable) {
      out.findings.push({
        id: 'lovable-default-meta',
        severity: 'warning',
        title: "Lovable's default description or preview image is still in place",
        why: 'Shared links will show Lovable branding instead of your app, which looks like a demo rather than a real product.',
        location: at(lovable),
        fixPrompt: `In ${where(at(lovable))} my app still has Lovable's default meta tags (description, og:image, twitter tags). Replace them with my own app name, description and a 1200×630 preview image.`,
      });
    }

    const viteFavicon = ctx.find(/href=["']\/vite\.svg["']/, appCode, 1)[0];
    if (viteFavicon) {
      out.findings.push({
        id: 'default-favicon',
        severity: 'warning',
        title: 'Your site icon is still the Vite logo',
        why: 'The little icon in the browser tab and bookmarks is the template\'s, not yours.',
        location: at(viteFavicon),
        fixPrompt: 'My app still uses the default vite.svg favicon. Help me add my own favicon (and an apple-touch-icon) and update index.html to use them.',
      });
    }

    // Description & social preview
    const hasDescription =
      ctx.find(/<meta[^>]+name=["']description["']|\bdescription\s*:\s*["'`][^"'`]{10,}|generateMetadata/i, htmlOrLayout, 1).length > 0 ||
      ctx.find(/<meta[^>]+name=["']description["']|\bdescription\s*:\s*["'`][^"'`]{10,}/i, appCode, 1).length > 0;
    if (!hasDescription) {
      out.findings.push({
        id: 'no-description',
        severity: 'warning',
        title: 'No page description',
        why: 'Google shows the description under your link in search results. Without one it picks random text from the page.',
        fixPrompt: "Add a meta description to my app (one or two sentences on what it does and who it's for) in the main layout / index.html, and per-page descriptions for the main pages.",
      });
    }

    const hasOgImage =
      ctx.hasPath(/(^|\/)(opengraph-image|twitter-image)\.(png|jpe?g|gif|tsx?|jsx?)$/) ||
      ctx.find(/og:image|twitter:image|openGraph\s*:\s*\{[\s\S]{0,600}?images/i, appCode, 1).length > 0;
    if (hasOgImage && !lovable) out.passed.push('Shared links show a preview image');
    else if (!hasOgImage) {
      out.findings.push({
        id: 'no-social-preview',
        severity: 'warning',
        title: 'No preview image when your link is shared',
        why: 'When someone shares your link on WhatsApp, X or LinkedIn, it shows an empty card instead of an image and title, so fewer people click.',
        fixPrompt: 'Add Open Graph and Twitter card tags to my app (title, description, and a 1200×630 preview image) so shared links show a nice preview card. Tell me how to test it with a link-preview checker.',
      });
    }

    // Hard-coded localhost URLs
    const localhost = ctx
      .find(/https?:\/\/(?:localhost|127\.0\.0\.1)(?::\d+)?/, (f) => appCode(f) && !CONFIG_OR_SCRIPT.test(f.path))
      .filter((m) => {
        const line = lineTextAt(m.file.content, m.index);
        return !/process\.env|import\.meta\.env|Deno\.env|\?\?|\|\||NODE_ENV|console\.|isDev|development/i.test(line);
      });
    if (localhost.length) {
      const m = localhost[0]!;
      out.findings.push({
        id: 'hardcoded-localhost',
        severity: 'warning',
        title: `Your app calls localhost${localhost.length > 1 ? ` in ${localhost.length} places` : ''}`,
        why: '"localhost" means "this computer". It works while you develop, but for real users it points at their own device, so the feature breaks.',
        location: at(m),
        fixPrompt:
          `My code has hard-coded localhost URLs (first one: ${where(at(m))}). Replace them with relative URLs (like "/api/...") or an environment variable for the base URL, ` +
          'so the app works both on my computer and when deployed. List every place you changed.',
      });
    }

    // Nice-to-haves
    const nextApp = ctx.hasPath(/(^|\/)app\/(?:.*\/)?page\.(?:t|j)sx?$/);
    const has404 = nextApp
      ? ctx.hasPath(/(^|\/)app\/(?:.*\/)?not-found\.(?:t|j)sx?$/)
      : ctx.hasPath(/(^|\/)(404|not-?found|\+error)\.(?:[tj]sx?|vue|svelte|html|astro)$/i) ||
        ctx.find(/path\s*[:=]\s*\{?\s*["']\*["']/, appCode, 1).length > 0;
    if (has404) out.passed.push('Has a "page not found" screen');
    else {
      out.manual.push({
        id: 'not-found-page',
        title: 'Add a friendly "page not found" screen',
        how: 'Visit a made-up URL on your live site. It should show your own 404 page with a link back home, not a blank or generic error page.',
      });
    }

    const hasRobots = ctx.hasPath(/(^|\/)(public\/|static\/)?robots\.txt$|(^|\/)app\/robots\.(t|j)sx?$/);
    const hasSitemap = ctx.hasPath(/(^|\/)(public\/|static\/)?sitemap.*\.xml$|(^|\/)app\/sitemap\.(t|j)sx?$/) || ctx.uses('next-sitemap');
    if (hasRobots && hasSitemap) out.passed.push('Has robots.txt and a sitemap for Google');
    else {
      out.manual.push({
        id: 'robots-sitemap',
        title: `Add ${!hasRobots && !hasSitemap ? 'robots.txt and a sitemap' : !hasRobots ? 'robots.txt' : 'a sitemap'} so Google can find your pages`,
        how: 'Then add your site to Google Search Console and submit the sitemap.',
      });
    }

    out.manual.push({
      id: 'phone-test',
      title: 'Open your live site on a real phone',
      how: 'Most visitors will be on mobile. Check sign-up, the main feature and checkout on a phone screen, with slow mobile data.',
    });

    return out;
  },
};
