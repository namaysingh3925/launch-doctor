import { detectAuth } from '../detect.js';
import type { ProjectContext, SourceFile } from '../project.js';
import type { Check, CheckOutput, ManualCheck } from '../types.js';
import { lineTextAt } from '../util.js';
import { appCode, at, emptyOutput, notApplicable, where } from './common.js';

const DEFAULT_TITLE =
  /<title>\s*(?:Vite \+ (?:React|Vue|Svelte|Preact|Lit|Solid|TS)(?: \+ TS)?|Vite App|React App|Create Next App|Lovable App|Nuxt App|SvelteKit App)\s*<\/title>|title\s*:\s*["'`]Create Next App["'`]|Generated by create next app/i;

const LOVABLE_DEFAULTS = /Lovable Generated Project|lovable\.dev\/opengraph-image|@lovable_dev|gpt-engineer/i;

const CONFIG_OR_SCRIPT =
  /(^|\/)(vite|next|nuxt|svelte|astro|playwright|vitest|jest|webpack|tailwind|postcss|eslint|tsup|rollup)\.config\.|(^|\/)(scripts|tools|seed|e2e)\/|(^|\/)seed\.|\.md$/i;

const htmlOrLayout = (f: SourceFile) =>
  appCode(f) &&
  (/\.html?$/i.test(f.path) ||
    /(^|\/)(app\/layout|_document|_app|app\.html|\+layout|nuxt\.config|layouts?\/)/i.test(f.path) ||
    /index\.html$/.test(f.path));

export const firstImpressionsCheck: Check = {
  id: 'first-impressions',
  name: 'First impressions',
  weight: 1,
  ids: [
    'default-title',
    'lovable-default-meta',
    'default-favicon',
    'no-description',
    'no-social-preview',
    'hardcoded-localhost',
    'not-found-page',
    'robots-sitemap',
    'phone-test',
    'mobile-placeholder-app-id',
    'android-cleartext-traffic',
    'ios-arbitrary-loads',
    'store-listing',
    'store-privacy-labels',
    'store-review-account',
    'device-test',
    'clerk-production-instance',
  ],
  run(ctx) {
    const frontend =
      ctx.files.some((f) => /\.html?$/i.test(f.path) && !/(^|\/)(docs|coverage)\//.test(f.path)) ||
      ctx.usesAny([
        'react',
        'vue',
        'svelte',
        'next',
        'nuxt',
        'astro',
        '@sveltejs/kit',
        'solid-js',
        'preact',
        '@angular/core',
      ]);
    if (!ctx.isMobileApp) {
      if (!ctx.isWebApp) return notApplicable('Not a web app');
      if (!frontend) return notApplicable('No website frontend found');
    }
    const out = emptyOutput();
    if (ctx.isWebApp && frontend) websiteImpressions(ctx, out);
    if (ctx.isMobileApp) mobileImpressions(ctx, out);
    if (ctx.uses('@clerk/')) out.manual.push(CLERK_PRODUCTION);
    return out;
  },
};

function websiteImpressions(ctx: ProjectContext, out: CheckOutput): void {
  // Default template titles
  const defaultTitle = ctx.find(DEFAULT_TITLE, appCode, 1)[0];
  if (defaultTitle) {
    const isDescription = /Generated by create next app/i.test(defaultTitle.match[0]);
    const shown = defaultTitle.match[0].replace(/<\/?title>|title\s*:\s*|["'`]/gi, '').trim();
    out.findings.push({
      id: 'default-title',
      severity: 'warning',
      title: isDescription ? `Your page description still says "${shown}"` : `Your browser tab still says "${shown}"`,
      why: isDescription
        ? "That's the starter template's description. Google shows it under your link in search results and shared links, and it makes the app look unfinished."
        : "That's the starter template's title. It shows in browser tabs, Google results and shared links, and makes the app look unfinished.",
      location: at(defaultTitle),
      fixPrompt: `My app still uses the template's default page title and description (${where(at(defaultTitle))}). Replace them with my app's real name and a one-sentence description of what it does, and set a title template so each page gets its own title.`,
    });
  }

  const lovable = ctx.find(LOVABLE_DEFAULTS, appCode, 1)[0];
  if (lovable) {
    out.findings.push({
      id: 'lovable-default-meta',
      severity: 'warning',
      title: "Lovable's default description or preview image is still in place",
      why: 'Shared links will show Lovable branding instead of your app, which looks like a demo rather than a real product.',
      location: at(lovable),
      fixPrompt: `In ${where(at(lovable))} my app still has Lovable's default meta tags (description, og:image, twitter tags). Replace them with my own app name, description and a 1200×630 preview image.`,
    });
  }

  const viteFavicon = ctx.find(/href=["']\/vite\.svg["']/, appCode, 1)[0];
  if (viteFavicon) {
    out.findings.push({
      id: 'default-favicon',
      severity: 'warning',
      title: 'Your site icon is still the Vite logo',
      why: "The little icon in the browser tab and bookmarks is the template's, not yours.",
      location: at(viteFavicon),
      fixPrompt:
        'My app still uses the default vite.svg favicon. Help me add my own favicon (and an apple-touch-icon) and update index.html to use them.',
    });
  }

  // Description & social preview
  const hasDescription =
    ctx.find(
      /<meta[^>]+name=["']description["']|\bdescription\s*:\s*["'`][^"'`]{10,}|generateMetadata/i,
      htmlOrLayout,
      1,
    ).length > 0 ||
    ctx.find(/<meta[^>]+name=["']description["']|\bdescription\s*:\s*["'`][^"'`]{10,}/i, appCode, 1).length > 0;
  if (!hasDescription) {
    out.findings.push({
      id: 'no-description',
      severity: 'warning',
      title: 'No page description',
      why: 'Google shows the description under your link in search results. Without one it picks random text from the page.',
      fixPrompt:
        "Add a meta description to my app (one or two sentences on what it does and who it's for) in the main layout / index.html, and per-page descriptions for the main pages.",
    });
  }

  const hasOgImage =
    ctx.hasPath(/(^|\/)(opengraph-image|twitter-image)\.(png|jpe?g|gif|tsx?|jsx?)$/) ||
    ctx.find(/og:image|twitter:image|openGraph\s*:\s*\{[\s\S]{0,600}?images/i, appCode, 1).length > 0;
  if (hasOgImage && !lovable) out.passed.push('Shared links show a preview image');
  else if (!hasOgImage) {
    out.findings.push({
      id: 'no-social-preview',
      severity: 'warning',
      title: 'No preview image when your link is shared',
      why: 'When someone shares your link on WhatsApp, X or LinkedIn, it shows an empty card instead of an image and title, so fewer people click.',
      fixPrompt:
        'Add Open Graph and Twitter card tags to my app (title, description, and a 1200×630 preview image) so shared links show a nice preview card. Tell me how to test it with a link-preview checker.',
    });
  }

  // Hard-coded localhost URLs
  const localhost = ctx
    .find(
      /https?:\/\/(?:localhost|127\.0\.0\.1)(?::\d+)?/,
      (f) => appCode(f) && !CONFIG_OR_SCRIPT.test(f.path) && !ctx.isMobileFile(f.path),
    )
    .filter((m) => {
      const line = lineTextAt(m.file.content, m.index);
      return !/process\.env|import\.meta\.env|Deno\.env|\?\?|\|\||NODE_ENV|console\.|isDev|development/i.test(line);
    });
  if (localhost.length) {
    const m = localhost[0]!;
    out.findings.push({
      id: 'hardcoded-localhost',
      severity: 'warning',
      title: `Your app calls localhost${localhost.length > 1 ? ` in ${localhost.length} places` : ''}`,
      why: '"localhost" means "this computer". It works while you develop, but for real users it points at their own device, so the feature breaks.',
      location: at(m),
      fixPrompt:
        `My code has hard-coded localhost URLs (first one: ${where(at(m))}). Replace them with relative URLs (like "/api/...") or an environment variable for the base URL, ` +
        'so the app works both on my computer and when deployed. List every place you changed.',
    });
  }

  // Nice-to-haves
  const nextApp = ctx.hasPath(/(^|\/)app\/(?:.*\/)?page\.(?:t|j)sx?$/);
  const has404 = nextApp
    ? ctx.hasPath(/(^|\/)app\/(?:.*\/)?not-found\.(?:t|j)sx?$/)
    : ctx.hasPath(/(^|\/)(404|not-?found|\+error)\.(?:[tj]sx?|vue|svelte|html|astro)$/i) ||
      ctx.find(/path\s*[:=]\s*\{?\s*["']\*["']/, appCode, 1).length > 0;
  if (has404) out.passed.push('Has a "page not found" screen');
  else {
    out.manual.push({
      id: 'not-found-page',
      title: 'Add a friendly "page not found" screen',
      how: 'Visit a made-up URL on your live site. It should show your own 404 page with a link back home, not a blank or generic error page.',
    });
  }

  const hasRobots = ctx.hasPath(/(^|\/)(public\/|static\/)?robots\.txt$|(^|\/)app\/robots\.(t|j)sx?$/);
  const hasSitemap =
    ctx.hasPath(/(^|\/)(public\/|static\/)?sitemap.*\.xml$|(^|\/)app\/sitemap\.(t|j)sx?$/) || ctx.uses('next-sitemap');
  if (hasRobots && hasSitemap) out.passed.push('Has robots.txt and a sitemap for Google');
  else {
    out.manual.push({
      id: 'robots-sitemap',
      title: `Add ${!hasRobots && !hasSitemap ? 'robots.txt and a sitemap' : !hasRobots ? 'robots.txt' : 'a sitemap'} so Google can find your pages`,
      how: 'Then add your site to Google Search Console and submit the sitemap.',
    });
  }

  out.manual.push({
    id: 'phone-test',
    title: 'Open your live site on a real phone',
    how: 'Most visitors will be on mobile. Check sign-up, the main feature and checkout on a phone screen, with slow mobile data.',
  });
}

const CLERK_PRODUCTION: ManualCheck = {
  id: 'clerk-production-instance',
  title: 'Switch Clerk to a production instance before launch',
  how: "A Clerk development instance is for testing: its sign-in screens show a \"Development mode\" badge and social sign-in uses Clerk's shared Google and GitHub credentials. In the Clerk Dashboard, create the production instance, add your domain's DNS records, set your own OAuth credentials, and use the pk_live_ and sk_live_ keys in your host's environment variables.",
};

/** ios.bundleIdentifier / android.package (Expo config) or package / applicationId (native) set to a template value. */
const PLACEHOLDER_APP_ID =
  /(?:bundleIdentifier|package|applicationId)["']?\s*[:=]\s*["'](com\.(?:anonymous|example|yourcompany|mycompany|test)\.[\w.-]+)["']/;
/** Addresses that only work on the developer's machine or network (10.0.2.2 is the Android emulator's name for it). */
const DEV_ADDRESS =
  /https?:\/\/(?:localhost|127\.0\.0\.1|10\.0\.2\.2|192\.168\.\d{1,3}\.\d{1,3}|172\.(?:1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3})(?::\d+)?/;
const isExpoConfig = (f: SourceFile) => /(^|\/)app\.(?:json|config\.[cm]?[jt]s)$/.test(f.path);
const isAndroidManifest = (f: SourceFile) =>
  /(^|\/)AndroidManifest\.xml$/.test(f.path) && !/(^|\/)src\/debug\//.test(f.path);
const isInfoPlist = (f: SourceFile) => /(^|\/)Info\.plist$/.test(f.path);

function mobileImpressions(ctx: ProjectContext, out: CheckOutput): void {
  const mobile = (f: SourceFile) => ctx.isMobileFile(f.path);

  const appId = ctx.find(PLACEHOLDER_APP_ID, (f) => mobile(f) && (isExpoConfig(f) || isAndroidManifest(f)), 1)[0];
  if (appId) {
    const id = appId.match[1]!;
    out.findings.push({
      id: 'mobile-placeholder-app-id',
      severity: 'warning',
      title: `Your app ID is still a placeholder (${id})`,
      why: 'The App Store and Google Play identify your app by this ID, and once you publish it can never change. Google Play refuses com.example IDs, and a placeholder looks unfinished everywhere it shows.',
      location: at(appId),
      fixPrompt:
        `My app's ID is still the placeholder "${id}" (${where(at(appId))}). Before my first store upload, change ios.bundleIdentifier and android.package in my Expo config ` +
        '(or the native iOS and Android projects) to a reverse domain I own, like com.mycompany.appname. ' +
        'Then tell me everything else that must match the new ID: EAS credentials, Firebase or Google service files, deep links and OAuth redirect URIs.',
    });
  }

  const cleartext = ctx.find(
    /usesCleartextTraffic["']?\s*[:=]\s*["']?true/,
    (f) => mobile(f) && (isExpoConfig(f) || isAndroidManifest(f)),
    1,
  )[0];
  if (cleartext) {
    out.findings.push({
      id: 'android-cleartext-traffic',
      severity: 'warning',
      title: 'Your Android app allows unencrypted HTTP connections',
      why: 'With cleartext traffic allowed, anyone on the same Wi-Fi can read or change what the app sends and receives, logins included. Android blocks it by default for that reason.',
      location: at(cleartext),
      fixPrompt:
        `In ${where(at(cleartext))} my Android app allows cleartext (http://) traffic. Please turn usesCleartextTraffic off and make every URL the app calls use https. ` +
        'If a development server truly needs http, allow it only in debug builds (the debug AndroidManifest, or a network security config for that one host).',
    });
  }

  const ats = ctx.find(
    /NSAllowsArbitraryLoads["']?\s*(?::\s*true|<\/key>\s*<true\s*\/>)/,
    (f) => mobile(f) && (isExpoConfig(f) || isInfoPlist(f)),
    1,
  )[0];
  if (ats) {
    out.findings.push({
      id: 'ios-arbitrary-loads',
      severity: 'warning',
      title: 'Your iOS app turns off HTTPS protection (NSAllowsArbitraryLoads)',
      why: "App Transport Security makes iOS refuse unencrypted connections. Turning it off lets anyone on the same network read or change the app's traffic, and Apple asks you to justify it during review.",
      location: at(ats),
      fixPrompt:
        `In ${where(at(ats))} my iOS app sets NSAllowsArbitraryLoads to true. Please remove it and make every URL the app calls use https. ` +
        'If one host truly needs an exception, add an NSExceptionDomains entry for just that host instead.',
    });
  }

  const devAddress = ctx
    .find(DEV_ADDRESS, (f) => mobile(f) && appCode(f) && !CONFIG_OR_SCRIPT.test(f.path))
    .filter((m) => {
      const line = lineTextAt(m.file.content, m.index);
      return !/process\.env|__DEV__|\?\?|\|\||NODE_ENV|console\.|isDev|development/i.test(line);
    });
  if (devAddress.length) {
    const m = devAddress[0]!;
    out.findings.push({
      id: 'hardcoded-localhost',
      severity: 'warning',
      title: `Your app calls a development address (${m.match[0]})${devAddress.length > 1 ? ` in ${devAddress.length} places` : ''}`,
      why: "That address only exists on your computer or your Wi-Fi (10.0.2.2 is the Android emulator's name for your computer). On a real user's phone it goes nowhere, so the feature breaks.",
      location: at(m),
      fixPrompt:
        `My app has hard-coded development URLs (first one: ${where(at(m))}). Replace them with one config value, like an EXPO_PUBLIC_API_URL environment variable, ` +
        'that points at my real https server in release builds and at my computer only during development. List every place you changed.',
    });
  }

  out.manual.push(
    {
      id: 'store-listing',
      title: 'Prepare the store listing',
      how: 'Your own app icon and splash screen (not the template ones), screenshots for the required screen sizes, a short description and a support URL. Both stores check these before approving the app.',
    },
    {
      id: 'store-privacy-labels',
      title: "Fill in Apple's App Privacy and Google Play's Data safety forms",
      how: 'List everything the app and its SDKs collect (analytics, crash reports, sign-in, ads). Answers that do not match what the app does are a common reason for rejection.',
    },
  );
  if (detectAuth(ctx)) {
    out.manual.push({
      id: 'store-review-account',
      title: 'Give the app reviewers a test account',
      how: 'Apple and Google reviewers have to sign in. Put a working demo login (and the steps to reach any paid features) in the review notes, or the app gets rejected.',
    });
  }
  out.manual.push({
    id: 'device-test',
    title: 'Test a release build on a real phone',
    how: 'Install a release build through TestFlight or a Google Play internal test, not Expo Go or a simulator. Try sign-up, the main feature, purchases, push notifications and links that open the app, on slow mobile data.',
  });
}
